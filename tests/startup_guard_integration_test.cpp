using namespace esphome::optimizer;
static int checks = 0;
static void check(bool ok, const char *message) {
  ++checks;
  if (!ok) { std::fprintf(stderr, "FAIL guard integration: %s\n", message); std::exit(1); }
}
static bool near(float a, float b) { return std::fabs(a - b) < 0.001f; }

int main() {
  Optimizer guard;
  ReturnGuidedStartup disabled;
  disabled.compressor_event(0, true, false, false, false, true);
  check(!disabled.calculate(0, false, true, 20.5f, 1, 15, 23, 24, 35).apply, "OFF does not intercept");
  check(near(guard.apply_flow_limits(OptimizerZone::ZONE_2, 23, 2.48f, 20.5f), 24), "OFF retains existing 24 C minimum");
  ReturnGuidedStartup startup;
  startup.compressor_event(0, true, false, false, true, true);
  auto request = startup.calculate(0, true, true, 20.5f, 1, 15, 23, 24, 35);
  auto applied = guard.apply_flow_limits(OptimizerZone::ZONE_2, request.target, 2.48f, 20.5f, request.minimum_override);
  check(near(applied, 21.5f), "21.5 C survives normal minimum during startup");
  const auto fractional = startup.calculate(1000, true, true, 20.54f, 1, 15, 23, 24, 35);
  check(near(guard.apply_flow_limits(OptimizerZone::ZONE_2, fractional.target, 2.48f, 20.54f, fractional.minimum_override), 21.5f),
        "temporary minimum does not undo the common 0.1 C rounding");
  check(near(guard.apply_flow_limits(OptimizerZone::ZONE_1, 21.5f, 2.48f, 20.5f, request.minimum_override), 24),
        "temporary minimum never affects Z1");
  guard.feed = 25.0f;
  applied = guard.apply_flow_limits(OptimizerZone::ZONE_2, request.target, 2.48f, 20.5f, request.minimum_override);
  check(near(applied, 25), "buffer guard holds feed above startup ceiling");
  for (int i = 1; i <= 20; ++i) {
    request = startup.calculate(i * 30000, true, true, 20.5f, 1, 15, 23, 24, 35);
    applied = guard.apply_flow_limits(OptimizerZone::ZONE_2, request.target, 2.48f, 20.5f, request.minimum_override);
    check(near(applied, 25), "repeated startup/guard evaluation does not ratchet or oscillate");
  }
  guard.tolerance.state = 5.0f;
  applied = guard.apply_flow_limits(OptimizerZone::ZONE_2, request.target, 2.48f, 20.5f, request.minimum_override);
  check(near(applied, 24), "tolerance still applies; compressor-stop guard retains feed-minus-1 floor");
  guard.zone_max = 23.0f;
  guard.tolerance.state = 0.0f;
  check(near(guard.apply_flow_limits(OptimizerZone::ZONE_2, request.target, 2.48f, 20.5f, request.minimum_override), 23),
        "configured maximum wins even when guard holds feed higher");
  guard.zone_max = 35.0f;
  guard.feed = 21.0f;
  ReturnGuidedStartup completion;
  completion.compressor_event(0, true, false, false, true, true);
  request = completion.calculate(899999, true, true, 20.5f, 1, 15, 26, 24, 35);
  check(near(guard.apply_flow_limits(OptimizerZone::ZONE_2, request.target, 2.48f, 20.5f, request.minimum_override), 21.5f),
        "startup below minimum before timeout");
  request = completion.calculate(899999, true, true, 23, 1, 15, 26, 24, 35);
  check(request.apply && completion.waiting_for_aa() && near(request.target, 24), "minimum reached");
  completion.resume_normal_aa();
  check(!completion.owns_flow() && near(guard.apply_flow_limits(OptimizerZone::ZONE_2, 26, 2.48f, 20.5f), 26),
        "regular AA resumes normal request without handover");
  std::printf("PASS: %d checks using production buffer and compressor-stop guard bodies.\n", checks);
}
